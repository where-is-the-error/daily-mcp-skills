def row_text(sido: str, values: tuple) -> str:
    district, day, people, homes, delta, zipcode, phone, area = values
    return (
        f"{sido},{district},{day},\"{people:,}\",\"{homes:,}\",{delta},{zipcode},"
        f"{phone},{area}㎡"
    )


def main() -> int:
    lines: list[str] = []
    lines.append("2024년 3분기 주민등록 인구현황")
    lines.append("(단위: 명, 세대, ㎡)")
    lines.append("시도,시군구,기준일,인구수,세대수,증감,우편번호,대표전화,면적")

    def block(name: str, rows: list[tuple]) -> None:
        people = homes = delta = 0
        for index, values in enumerate(rows):
            district, day, p, h, d, zipcode, phone, area = values
            lines.append(row_text(name, values))
            people += p
            homes += h
            delta += d
            if name == "서울" and district == "성동구":
                # 완전히 같은 행이 한 번 더 들어간 경우(원본 시스템의 중복 적재)
                lines.append(row_text(name, values))
            if name == "경기" and district == "안양시":
                # 따옴표 없는 쉼표 — '안양시, 동안구' 가 두 칸으로 갈라진다
                lines.append(f"{name},안양시, 동안구,2024-09-30,\"120,112\",60012,-88,13900,031-8045-1114,0㎡")
            if name == "경기" and district == "화성시":
                # 전각 숫자 + 앞뒤 공백
                lines.append(f"{name}, 화성시 ,2024-09-30,\"１２０,334\",50012,＋　301,18201,031-369-1114,0㎡")
            if name == "부산" and district == "동래구":
                # 줄 중간 빈 줄
                lines.append("")
        lines.append(f"{name},소계,\"2024-09-30\",\"{people:,}\",\"{homes:,}\",{delta},,,")

    block("서울", SEOUL)
    block("경기", GYEONGGI)
    block("부산", BUSAN)
    lines.append("※ 2024년 9월 30일 주민등록 기준, 세대수는 외국인 제외")
    lines.append("출처: 행정안전부 주민등록 인구통계")

    text = "\n".join(lines) + "\n"
    (HERE / "raw_population.csv").write_bytes(text.encode("cp949"))
    print(HERE / "raw_population.csv")

    build_xlsx()
    return 0


def build_xlsx() -> None:
    """병합 칸이 있는 엑셀 — 상위 머리글과 시도 병합."""
    import openpyxl

    book = openpyxl.Workbook()
    sheet = book.active
    sheet.title = "인구"
    sheet["A1"] = "2024년 인구 (간이)"
    sheet["A3"] = "시도"
    sheet["B3"] = "시군구"
    sheet["C3"] = "인구수"
    sheet["D3"] = "세대수"
    sheet.merge_cells("C3:D3")
    sheet["C3"] = "규모"
    sheet["E3"] = "우편번호"
    rows = [
        ("서울", "종로구", 132456, 61234, "11010"),
        ("서울", "중구", 125001, 58912, "04530"),
        ("서울", "용산구", 218904, 101233, "04389"),
        ("경기", "수원시", 1190012, 501223, "16223"),
        ("경기", "성남시", 912334, 401112, "13490"),
        ("경기", "고양시", 1052334, 440221, "10400"),
    ]
    # 시도 병합: 서울 3행, 경기 3행
    start = 4
    for district_row, (sido, *rest) in enumerate(rows):
        sheet.cell(row=start + district_row, column=1, value=sido if district_row in (0, 3) else None)
        for col, value in enumerate(rest, start=2):
            sheet.cell(row=start + district_row, column=col, value=value)
    sheet.merge_cells(start_row=4, end_row=6, start_column=1, end_column=1)
    sheet.merge_cells(start_row=7, end_row=9, start_column=1, end_column=1)
    sheet["A11"] = "합계"
    sheet["C11"] = sum(r[2] for r in rows)
    sheet["D11"] = sum(r[3] for r in rows)
    path = HERE / "merged_population.xlsx"
    book.save(path)
    print(path)


